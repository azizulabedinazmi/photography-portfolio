#!/usr/bin/env node
/**
 * Creates fast-loading WebP copies of every local portfolio photo.
 * Runs on every Netlify deploy (see netlify.toml) and can be run locally: `node scripts/build-images.js`
 *
 *   dist/assets/Photography/<name>.jpg
 *     -> dist/assets/Photography/_web/<name>-480.webp   (filmstrip, small phones)
 *     -> dist/assets/Photography/_web/<name>-960.webp   (gallery grid)
 *     -> dist/assets/Photography/_web/<name>-1600.webp  (full-screen viewer)
 *
 * Also writes dist/image-variants.js, which the homepage uses to pick the right size.
 * Originals are never modified. Output is git-ignored and rebuilt on deploy.
 */

const fs = require('fs');
const path = require('path');
const sharp = require('sharp');
const exifReader = require('exif-reader');

// Real camera settings read from the photo file itself (null when the file has none).
function readExif(buf) {
  if (!buf) return null;
  let e;
  try { e = exifReader(buf); } catch { return null; }
  const img = e.Image || e.image || {};
  const ph = e.Photo || e.exif || {};
  const out = {};
  const make = (img.Make || '').trim();
  const model = (img.Model || '').trim();
  if (model) out.camera = model.toLowerCase().startsWith(make.toLowerCase()) || !make ? model : `${make} ${model}`;
  if (ph.LensModel) out.lens = String(ph.LensModel).trim();
  if (ph.FocalLength) out.focal = `${Math.round(ph.FocalLength)}mm`;
  if (ph.FNumber) out.aperture = `f/${+Number(ph.FNumber).toFixed(1)}`;
  if (ph.ExposureTime) {
    const t = Number(ph.ExposureTime);
    out.shutter = t >= 1 ? `${+t.toFixed(1)}s` : `1/${Math.round(1 / t)}s`;
  }
  const iso = ph.ISOSpeedRatings || ph.PhotographicSensitivity;
  if (iso) out.iso = `ISO ${Array.isArray(iso) ? iso[0] : iso}`;
  const taken = ph.DateTimeOriginal || img.DateTime;
  if (taken instanceof Date && !isNaN(taken)) out.taken = taken.toISOString().slice(0, 10);
  if (img.Software) out.software = String(img.Software).replace(/\s*\((Windows|Macintosh|Mac OS)\)\s*$/i, '').trim();
  return Object.keys(out).length ? out : null;
}

const ROOT = path.join(__dirname, '..');
const SRC_DIR = 'dist/assets/Photography';
const OUT_DIR = `${SRC_DIR}/_web`;
const WIDTHS = [480, 960, 1600];
const QUALITY = 78;
const EXT = /\.(jpe?g|png|webp|tiff?)$/i;

const abs = (p) => path.join(ROOT, p);
const slug = (name) => name.replace(EXT, '').replace(/[^\w.-]+/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '');

async function variantsFor(file) {
  const src = `${SRC_DIR}/${file}`;
  const base = slug(file);
  const srcStat = fs.statSync(abs(src));
  const image = sharp(abs(src), { failOn: 'none' }).rotate(); // respect EXIF orientation
  const meta = await image.metadata();
  const swap = (meta.orientation || 1) >= 5;
  const width = swap ? meta.height : meta.width;
  const height = swap ? meta.width : meta.height;

  const entry = { w: width, h: height, srcset: [] };
  const exif = readExif(meta.exif);
  if (exif) entry.exif = exif;
  for (const target of WIDTHS) {
    const w = Math.min(target, width);
    const out = `${OUT_DIR}/${base}-${target}.webp`;
    const outAbs = abs(out);
    const fresh = fs.existsSync(outAbs) && fs.statSync(outAbs).mtimeMs >= srcStat.mtimeMs;
    if (!fresh) {
      await sharp(abs(src), { failOn: 'none' })
        .rotate()
        .resize({ width: w, withoutEnlargement: true })
        .webp({ quality: QUALITY, effort: 5 })
        .toFile(outAbs);
    }
    entry.srcset.push([out, w]);
    if (w === width) break; // original is smaller than the next size; no point going bigger
  }
  return [src, entry];
}

(async () => {
  const started = Date.now();
  fs.mkdirSync(abs(OUT_DIR), { recursive: true });
  const files = fs.readdirSync(abs(SRC_DIR)).filter((f) => EXT.test(f) && fs.statSync(abs(`${SRC_DIR}/${f}`)).isFile());

  const map = {};
  let before = 0, after = 0;
  // A few at a time keeps memory low on the build machine.
  for (let i = 0; i < files.length; i += 4) {
    const batch = await Promise.all(files.slice(i, i + 4).map((f) => variantsFor(f).catch((e) => {
      console.warn(`  ! skipped ${f}: ${e.message}`);
      return null;
    })));
    for (const r of batch) {
      if (!r) continue;
      const [src, entry] = r;
      map[src] = entry;
      before += fs.statSync(abs(src)).size;
      const mid = entry.srcset.find(([, w]) => w >= 960) || entry.srcset[entry.srcset.length - 1];
      after += fs.statSync(abs(mid[0])).size;
    }
  }

  fs.writeFileSync(abs('dist/image-variants.js'),
    `/* GENERATED by scripts/build-images.js. Maps each original photo to its WebP sizes. */\n` +
    `window.IMAGE_VARIANTS = ${JSON.stringify(map)};\n`);

  const mb = (n) => (n / 1048576).toFixed(1);
  console.log(`Image build: ${Object.keys(map).length} photos, originals ${mb(before)} MB -> grid size ${mb(after)} MB (${((Date.now() - started) / 1000).toFixed(1)}s).`);
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
