#!/usr/bin/env node
/**
 * Keeps search-engine data in sync with dist/gallery-data.json (the file Decap CMS edits).
 * Runs on every Netlify deploy (see netlify.toml) and can be run locally: `node scripts/build-seo.js`
 *
 *  1. dist/gallery-data.js  – regenerated from the JSON so the homepage always shows the latest edits
 *  2. sitemap.xml           – lists every gallery image (with Google's image sitemap extension)
 *  3. index.html            – schema.org ImageGallery JSON-LD with each photo's name and alt text
 *
 * Each photo is described only by who/what is in it (no photographer name or credit), so a search for a
 * person's name finds their photo, but a search for the photographer's name doesn't pull up every image.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SITE = 'https://azmi.is-cool.dev';
const START = '<!-- SEO:GALLERY:START (generated by scripts/build-seo.js; do not edit by hand) -->';
const END = '<!-- SEO:GALLERY:END -->';

const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const write = (f, s) => fs.writeFileSync(path.join(ROOT, f), s);

const raw = JSON.parse(read('dist/gallery-data.json'));
const items = Array.isArray(raw) ? raw : raw.items || [];

function absoluteUrl(src) {
  if (!src) return null;
  const s = String(src).trim();
  if (/^https?:\/\//i.test(s)) return s;
  const drive = s.match(/\/d\/([a-zA-Z0-9_-]{10,})/) || (/^[a-zA-Z0-9_-]{25,}$/.test(s) ? [null, s] : null);
  if (drive) return `https://lh3.googleusercontent.com/d/${drive[1]}=w1600`;
  return SITE + '/' + encodeURI(s.replace(/^\.?\//, ''));
}

const xml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// Every photo, including extra frames inside a series.
const images = [];
const seen = new Set();
for (const it of items) {
  const srcs = [it.src, ...(Array.isArray(it.seriesExtra) ? it.seriesExtra : [])];
  srcs.forEach((src, i) => {
    const url = absoluteUrl(typeof src === 'string' ? src : src && src.image);
    if (!url || seen.has(url)) return;
    seen.add(url);
    images.push({
      url,
      name: i === 0 ? it.title : `${it.title} (${i + 1})`,
      alt: it.alt || it.title,
      keywords: it.tags || ''
    });
  });
}

// 1. gallery-data.js
write('dist/gallery-data.js',
  `/**\n * Azizul Abedin Azmi - Photography Portfolio Gallery Dataset\n * GENERATED from dist/gallery-data.json by scripts/build-seo.js.\n * Edit the JSON (or use Decap CMS at /admin/) instead of this file.\n */\n\nwindow.GALLERY_DATA = ${JSON.stringify(items, null, 2)};\n`);

// 2. sitemap.xml
const today = new Date().toISOString().slice(0, 10);
const imageTags = images.map((im) => `    <image:image>\n      <image:loc>${xml(im.url)}</image:loc>\n    </image:image>`).join('\n');
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
  <url>
    <loc>${SITE}/</loc>
    <lastmod>${today}</lastmod>
    <changefreq>weekly</changefreq>
    <priority>1.0</priority>
${imageTags}
  </url>
  <url>
    <loc>${SITE}/dist/about_me.html</loc>
    <lastmod>${today}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.8</priority>
  </url>
  <url>
    <loc>${SITE}/dist/contact.html</loc>
    <lastmod>${today}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.8</priority>
  </url>
</urlset>
`);

// 3. JSON-LD in index.html
const ld = {
  '@context': 'https://schema.org',
  '@type': 'ImageGallery',
  name: '〘卂乙爪丨〙ヅ - Portfolio',
  url: `${SITE}/`,
  image: images.map((im) => ({
    '@type': 'ImageObject',
    contentUrl: im.url,
    name: im.name,
    description: im.alt,
    keywords: im.keywords
  }))
};
const block = `${START}\n  <script type="application/ld+json">\n${JSON.stringify(ld).replace(/</g, '\\u003c')}\n  </script>\n  ${END}`;

let html = read('index.html');
const a = html.indexOf(START.slice(0, 22));
const b = html.indexOf(END);
if (a !== -1 && b !== -1) {
  html = html.slice(0, a) + block + html.slice(b + END.length);
} else {
  html = html.replace('</head>', `  ${block}\n</head>`);
}
write('index.html', html);

console.log(`SEO build: ${items.length} gallery items, ${images.length} images in sitemap and JSON-LD.`);
