const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'dist_site');

const PHOTO_DIR = path.join(ROOT, 'dist', 'assets', 'Photography');
const ART_DIR = path.join(ROOT, 'dist', 'assets', 'Art');
const ORIGINAL = /\.(jpe?g|png|webp|tiff?|heic)$/i;
// Full-size photo originals live in private R2 storage and are never published;
// only their WebP copies in Photography/_web/ are.
// Same for the digital-art masters mirrored from R2 (dist/assets/Art/).
const isPhotoOriginal = (p) => (path.dirname(p) === PHOTO_DIR || path.dirname(p) === ART_DIR) && ORIGINAL.test(p);

function copyRecursiveSync(src, dest) {
  if (!fs.existsSync(src)) return;
  const stats = fs.statSync(src);
  if (stats.isDirectory()) {
    if (!fs.existsSync(dest)) fs.mkdirSync(dest, { recursive: true });
    fs.readdirSync(src).forEach((childItemName) => {
      copyRecursiveSync(path.join(src, childItemName), path.join(dest, childItemName));
    });
  } else if (isPhotoOriginal(src)) {
    return;
  } else {
    const parent = path.dirname(dest);
    if (!fs.existsSync(parent)) fs.mkdirSync(parent, { recursive: true });
    fs.copyFileSync(src, dest);
  }
}

console.log('Postbuild: syncing static directories into dist_site...');

// Ensure dist_site exists
if (!fs.existsSync(OUT)) fs.mkdirSync(OUT, { recursive: true });

// 1. Copy dist/assets into dist_site/dist/assets and dist_site/assets
copyRecursiveSync(path.join(ROOT, 'dist/assets'), path.join(OUT, 'dist/assets'));
copyRecursiveSync(path.join(ROOT, 'dist/assets'), path.join(OUT, 'assets'));

// 2. Copy gallery data & variants into dist_site/dist/
['gallery-data.json', 'gallery-data.js', 'image-variants.js'].forEach((file) => {
  const p = path.join(ROOT, 'dist', file);
  if (fs.existsSync(p)) {
    fs.copyFileSync(p, path.join(OUT, 'dist', file));
  }
});

// 3. Copy the admin suite into dist_site
copyRecursiveSync(path.join(ROOT, 'admin'), path.join(OUT, 'admin'));

// 4. Copy SEO and root config files
['robots.txt', 'sitemap.xml', 'ads.txt'].forEach((file) => {
  const p = path.join(ROOT, file);
  if (fs.existsSync(p)) {
    fs.copyFileSync(p, path.join(OUT, file));
  }
});

// 5. Old links to a full-size original (search engines, shared links, the Studio
//    preview grid) redirect to its largest WebP copy instead.
const variantsFile = path.join(ROOT, 'dist', 'image-variants.js');
if (fs.existsSync(variantsFile)) {
  const text = fs.readFileSync(variantsFile, 'utf8');
  const variants = JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1));
  const lines = ['# GENERATED by scripts/copy-assets.js: full-size originals -> published WebP copies'];
  for (const [src, v] of Object.entries(variants)) {
    if (/^https?:\/\//i.test(src)) continue; // digital art, keyed by its original URL
    const best = v.srcset[v.srcset.length - 1][0];
    const to = encodeURI('/' + best);
    lines.push(`${encodeURI('/' + src)}  ${to}  301`);
    lines.push(`${encodeURI('/' + src.replace(/^dist\//, ''))}  ${to}  301`);
  }
  fs.writeFileSync(path.join(OUT, '_redirects'), lines.join('\n') + '\n');
  console.log(`Postbuild: ${(lines.length - 1) / 2} original-photo redirects written.`);
}

console.log('Postbuild: sync complete.');
